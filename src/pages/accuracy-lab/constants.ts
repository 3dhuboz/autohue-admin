// ── RGB → LAB conversion (matching server.js) ──
function rgbToXyz(r: number, g: number, b: number): [number, number, number] {
  let rr = r / 255, gg = g / 255, bb = b / 255;
  rr = rr > 0.04045 ? Math.pow((rr + 0.055) / 1.055, 2.4) : rr / 12.92;
  gg = gg > 0.04045 ? Math.pow((gg + 0.055) / 1.055, 2.4) : gg / 12.92;
  bb = bb > 0.04045 ? Math.pow((bb + 0.055) / 1.055, 2.4) : bb / 12.92;
  rr *= 100; gg *= 100; bb *= 100;
  return [
    rr * 0.4124564 + gg * 0.3575761 + bb * 0.1804375,
    rr * 0.2126729 + gg * 0.7151522 + bb * 0.0721750,
    rr * 0.0193339 + gg * 0.1191920 + bb * 0.9503041,
  ];
}

function xyzToLab(x: number, y: number, z: number): [number, number, number] {
  const refX = 95.047, refY = 100.0, refZ = 108.883;
  let xx = x / refX, yy = y / refY, zz = z / refZ;
  const f = (t: number) => t > 0.008856 ? Math.pow(t, 1 / 3) : 7.787 * t + 16 / 116;
  xx = f(xx); yy = f(yy); zz = f(zz);
  return [116 * yy - 16, 500 * (xx - yy), 200 * (yy - zz)];
}

export function rgbToLab(r: number, g: number, b: number): [number, number, number] {
  const [x, y, z] = rgbToXyz(r, g, b);
  return xyzToLab(x, y, z);
}

// ── CIEDE2000 Delta-E (matching server.js) ──
export function deltaE2000(lab1: number[], lab2: number[]): number {
  const [L1, a1, b1] = lab1;
  const [L2, a2, b2] = lab2;
  const avg_Lp = (L1 + L2) / 2;
  const C1 = Math.sqrt(a1 * a1 + b1 * b1);
  const C2 = Math.sqrt(a2 * a2 + b2 * b2);
  const avg_C = (C1 + C2) / 2;
  const G = 0.5 * (1 - Math.sqrt(Math.pow(avg_C, 7) / (Math.pow(avg_C, 7) + Math.pow(25, 7))));
  const a1p = a1 * (1 + G), a2p = a2 * (1 + G);
  const C1p = Math.sqrt(a1p * a1p + b1 * b1);
  const C2p = Math.sqrt(a2p * a2p + b2 * b2);
  const avg_Cp = (C1p + C2p) / 2;
  let h1p = Math.atan2(b1, a1p) * 180 / Math.PI; if (h1p < 0) h1p += 360;
  let h2p = Math.atan2(b2, a2p) * 180 / Math.PI; if (h2p < 0) h2p += 360;
  const dLp = L2 - L1, dCp = C2p - C1p;
  let dhp: number;
  if (C1p * C2p === 0) dhp = 0;
  else if (Math.abs(h2p - h1p) <= 180) dhp = h2p - h1p;
  else if (h2p - h1p > 180) dhp = h2p - h1p - 360;
  else dhp = h2p - h1p + 360;
  const dHp = 2 * Math.sqrt(C1p * C2p) * Math.sin(dhp * Math.PI / 360);
  let avg_Hp: number;
  if (C1p * C2p === 0) avg_Hp = h1p + h2p;
  else if (Math.abs(h1p - h2p) <= 180) avg_Hp = (h1p + h2p) / 2;
  else if (h1p + h2p < 360) avg_Hp = (h1p + h2p + 360) / 2;
  else avg_Hp = (h1p + h2p - 360) / 2;
  const T = 1 - 0.17 * Math.cos((avg_Hp - 30) * Math.PI / 180)
    + 0.24 * Math.cos(2 * avg_Hp * Math.PI / 180)
    + 0.32 * Math.cos((3 * avg_Hp + 6) * Math.PI / 180)
    - 0.20 * Math.cos((4 * avg_Hp - 63) * Math.PI / 180);
  const SL = 1 + 0.015 * Math.pow(avg_Lp - 50, 2) / Math.sqrt(20 + Math.pow(avg_Lp - 50, 2));
  const SC = 1 + 0.045 * avg_Cp;
  const SH = 1 + 0.015 * avg_Cp * T;
  const RT = -2 * Math.sqrt(Math.pow(avg_Cp, 7) / (Math.pow(avg_Cp, 7) + Math.pow(25, 7)))
    * Math.sin(60 * Math.exp(-Math.pow((avg_Hp - 275) / 25, 2)) * Math.PI / 180);
  return Math.sqrt(
    Math.pow(dLp / SL, 2) + Math.pow(dCp / SC, 2) + Math.pow(dHp / SH, 2)
    + RT * (dCp / SC) * (dHp / SH)
  );
}

// ── Pre-computed LAB reference palette ──
export const CAR_COLORS_LAB: Record<string, number[][]> = {};
for (const [category, rgbSamples] of Object.entries(CAR_COLORS_RGB)) {
  CAR_COLORS_LAB[category] = rgbSamples.map(([r, g, b]) => rgbToLab(r, g, b));
}

// ── Compute min boundary distance between two color category palettes ──
export function paletteBoundaryDistance(catA: string, catB: string): number {
  const labA = CAR_COLORS_LAB[catA];
  const labB = CAR_COLORS_LAB[catB];
  if (!labA || !labB) return Infinity;
  let minDist = Infinity;
  for (const a of labA) {
    for (const b of labB) {
      const d = deltaE2000(a, b);
      if (d < minDist) minDist = d;
    }
  }
  return minDist;
}
